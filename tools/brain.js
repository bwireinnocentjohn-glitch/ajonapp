function generateBusinessIdea() {
  var attempts = 0;
  while (attempts < 30) {
    var problem = pickFresh(BRAIN_PROBLEMS, BRAIN.lastIdeas, 40);
    var skill = BRAIN_SKILLS[Math.floor(Math.random() * BRAIN_SKILLS.length)];
    var location = BRAIN_LOCATIONS[Math.floor(Math.random() * BRAIN_LOCATIONS.length)];
    var trend = BRAIN_TRENDS[Math.floor(Math.random() * BRAIN_TRENDS.length)];
    var cap = Math.max(30000, Math.floor(BRAIN.capital * 0.4 / 1000) * 1000);
    var hash = problem + "|" + location + "|" + trend;
    if (BRAIN.usedIdeaHashes[hash]) { attempts++; continue; }
    BRAIN.usedIdeaHashes[hash] = 1;
    BRAIN.lastIdeas.push(problem);
    if (BRAIN.lastIdeas.length > 100) BRAIN.lastIdeas = BRAIN.lastIdeas.slice(-100);
    return { name: problem, location: location, skill: skill, capital: cap, trend: trend };
  }
  return null;
}

