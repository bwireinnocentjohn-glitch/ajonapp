function pickFresh(arr, lastArr, windowSize) {
  windowSize = windowSize || 20;
  var recent = lastArr.slice(-windowSize);
  var candidates = arr.filter(function (x) { return recent.indexOf(x) === -1; });
  if (!candidates.length) candidates = arr;
  return candidates[Math.floor(Math.random() * candidates.length)];
}

function nextTopic(currentTopic) {
  var chain = BRAIN_TOPIC_CHAINS[currentTopic];
  if (!chain || !chain.length) chain = Object.keys(BRAIN_TOPIC_CHAINS);
  var recent = BRAIN.lastTopics.slice(-6);
  var candidates = chain.filter(function (x) { return recent.indexOf(x) === -1; });
  if (!candidates.length) candidates = chain;
  var next = candidates[Math.floor(Math.random() * candidates.length)];
  BRAIN.lastTopics.push(next);
  if (BRAIN.lastTopics.length > 60) BRAIN.lastTopics = BRAIN.lastTopics.slice(-60);
  return next;
}

